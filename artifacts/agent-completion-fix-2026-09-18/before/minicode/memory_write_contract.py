"""Strict, content-free contracts for durable Memory write outcomes.

The reflection pipeline may handle content-bearing claims, but the durable
receipt used for replay and observation carries only opaque identities,
authority digests, and closed-vocabulary outcomes.  This keeps persisted
receipts safe to inspect while binding a retry to the exact write request.
"""

from __future__ import annotations

import hashlib
import json
import re
import uuid
from collections.abc import Mapping
from dataclasses import dataclass, field, replace

from minicode.memory_blob_store import MemoryBlobReference
from minicode.memory_provenance import is_memory_entry_id

MEMORY_AUTHORITY_RECEIPT_VERSION = 1
MEMORY_AUTHORITY_RECEIPT_REFERENCE_VERSION = 1
MEMORY_WRITE_RESULT_VERSION = 1

MAX_MEMORY_CLAIMS_PER_BATCH = 64
MAX_MEMORY_MATERIALIZATIONS_PER_RECEIPT = 64
MAX_SUPERSEDED_ENTRY_IDS = 16
MAX_MEMORY_WRITE_REASON_CODES = 32
MAX_MEMORY_AUTHORITY_RECEIPT_BYTES = 64 * 1024
MAX_PROJECT_FACT_CHANGES_PER_WRITE = 256

MEMORY_MATERIALIZATION_DISPOSITIONS = frozenset(
    {
        "created",
        "reinforced",
        "rejected_existing",
        "rejected_retention",
    }
)
MEMORY_AUTHORITY_SCOPES = frozenset({"project", "user"})
MEMORY_AUTHORITY_KINDS = frozenset(
    {"lesson", "conversation_fact", "none"}
)
PROJECT_FACTS_EFFECT_STATUSES = frozenset(
    {"not_applicable", "committed", "replayed", "failed", "skipped"}
)

_MEMORY_OPERATION_ID_RE = re.compile(r"^memoryop_[0-9a-f]{32}$")
_DIGEST_RE = re.compile(r"^[0-9a-f]{64}$")
_CLAIM_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$")
# Authority files can retain older, human-assigned safe IDs.  A write receipt,
# however, may name only IDs generated by the canonical materializer; this is
# a deliberately narrower subtype rather than another generic ID contract.
_MATERIALIZED_ENTRY_ID_RE = re.compile(
    r"^(?:user|project|local)-[0-9]{1,20}(?:-[0-9a-f]{8})?$"
)
_REASON_CODE_RE = re.compile(r"^[a-z][a-z0-9_]{0,127}$")
_AUTHORITY_RECEIPT_RESULT_TYPE = "MemoryAuthorityCommit.v1"

_MATERIALIZATION_FIELDS = frozenset(
    {
        "claimId",
        "entryId",
        "authorityDigest",
        "disposition",
        "supersededEntryIds",
    }
)
_AUTHORITY_COMMIT_FIELDS = frozenset(
    {
        "receiptVersion",
        "resultType",
        "operationId",
        "payloadDigest",
        "scope",
        "replayed",
        "materializations",
        "rejectedClaimIds",
    }
)
_AUTHORITY_RECEIPT_REFERENCE_FIELDS = frozenset(
    {
        "referenceVersion",
        "operationId",
        "payloadDigest",
        "scope",
        "blob",
    }
)
_PROJECT_FACTS_EFFECT_FIELDS = frozenset(
    {"status", "addedCount", "updatedCount", "failureCode"}
)


def new_memory_operation_id() -> str:
    """Return a fresh opaque identity for one logical Memory write."""
    return f"memoryop_{uuid.uuid4().hex}"


def _require_string(value: object, *, label: str, pattern: re.Pattern[str]) -> str:
    if not isinstance(value, str):
        raise TypeError(f"{label} must be a string")
    if pattern.fullmatch(value) is None:
        raise ValueError(f"{label} is invalid")
    return value


def _require_operation_id(value: object) -> str:
    return _require_string(
        value,
        label="Memory operation ID",
        pattern=_MEMORY_OPERATION_ID_RE,
    )


def _require_digest(value: object, *, label: str) -> str:
    return _require_string(value, label=label, pattern=_DIGEST_RE)


def _require_claim_id(value: object) -> str:
    return _require_string(value, label="Memory claim ID", pattern=_CLAIM_ID_RE)


def _require_entry_id(value: object) -> str:
    if not isinstance(value, str):
        raise TypeError("Memory entry ID must be a string")
    if (
        not is_memory_entry_id(value)
        or _MATERIALIZED_ENTRY_ID_RE.fullmatch(value) is None
    ):
        raise ValueError("Memory entry ID is invalid")
    return value


def _require_reason_code(value: object, *, label: str) -> str:
    return _require_string(value, label=label, pattern=_REASON_CODE_RE)


def _require_counter(value: object, *, label: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"{label} must be an integer")
    if value < 0 or value > MAX_PROJECT_FACT_CHANGES_PER_WRITE:
        raise ValueError(f"{label} is out of range")
    return value


@dataclass(frozen=True, slots=True, kw_only=True)
class MemoryMaterialization:
    """Content-free durable outcome for one validated reflection claim."""

    claim_id: str
    entry_id: str | None
    authority_digest: str | None
    disposition: str
    superseded_entry_ids: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        _require_claim_id(self.claim_id)
        if self.disposition not in MEMORY_MATERIALIZATION_DISPOSITIONS:
            raise ValueError("Memory materialization disposition is invalid")
        if not isinstance(self.superseded_entry_ids, tuple):
            raise TypeError("superseded_entry_ids must be a tuple")
        if len(self.superseded_entry_ids) > MAX_SUPERSEDED_ENTRY_IDS:
            raise ValueError("Memory materialization supersedes too many entries")
        seen_superseded: set[str] = set()
        for entry_id in self.superseded_entry_ids:
            _require_entry_id(entry_id)
            if entry_id in seen_superseded:
                raise ValueError("superseded_entry_ids contains a duplicate")
            seen_superseded.add(entry_id)

        materialized = self.disposition in {"created", "reinforced"}
        references_existing = self.disposition == "rejected_existing"
        if materialized or references_existing:
            if self.entry_id is None or self.authority_digest is None:
                raise ValueError(
                    "this Memory disposition requires an entry authority"
                )
            _require_entry_id(self.entry_id)
            _require_digest(
                self.authority_digest,
                label="Memory authority digest",
            )
        elif self.entry_id is not None or self.authority_digest is not None:
            raise ValueError(
                "rejected_retention cannot claim a durable entry authority"
            )

        if self.entry_id is not None and self.entry_id in seen_superseded:
            raise ValueError("a Memory entry cannot supersede itself")
        if self.disposition != "created" and self.superseded_entry_ids:
            raise ValueError(
                "only a created Memory entry may supersede prior entries"
            )

    @property
    def remains_materialized(self) -> bool:
        """Whether this outcome names an entry eligible for projection."""
        return self.disposition in {"created", "reinforced"}

    def to_dict(self) -> dict[str, object]:
        """Return the closed content-free materialization document."""
        return {
            "claimId": self.claim_id,
            "entryId": self.entry_id,
            "authorityDigest": self.authority_digest,
            "disposition": self.disposition,
            "supersededEntryIds": list(self.superseded_entry_ids),
        }

    @classmethod
    def from_dict(cls, value: object) -> MemoryMaterialization:
        """Parse one strict materialization document without repair."""
        if not isinstance(value, Mapping) or set(value) != _MATERIALIZATION_FIELDS:
            raise ValueError("Memory materialization has an invalid schema")
        raw_superseded = value.get("supersededEntryIds")
        if not isinstance(raw_superseded, list):
            raise TypeError("supersededEntryIds must be a list")
        return cls(
            claim_id=value.get("claimId"),  # type: ignore[arg-type]
            entry_id=value.get("entryId"),  # type: ignore[arg-type]
            authority_digest=value.get("authorityDigest"),  # type: ignore[arg-type]
            disposition=value.get("disposition"),  # type: ignore[arg-type]
            superseded_entry_ids=tuple(raw_superseded),
        )


@dataclass(frozen=True, slots=True, kw_only=True)
class MemoryAuthorityCommit:
    """Canonical receipt for one atomic, single-scope Memory authority write.

    ``replayed`` is runtime state.  Canonical receipt serialization always
    writes it as ``false`` so replaying an existing receipt cannot change its
    bytes or digest.  A reader calls :meth:`as_replay` after loading the stored
    receipt when reporting a duplicate operation.
    """

    operation_id: str
    payload_digest: str
    scope: str
    materializations: tuple[MemoryMaterialization, ...] = ()
    rejected_claim_ids: tuple[str, ...] = ()
    replayed: bool = False
    receipt_version: int = MEMORY_AUTHORITY_RECEIPT_VERSION

    def __post_init__(self) -> None:
        _require_operation_id(self.operation_id)
        _require_digest(self.payload_digest, label="Memory payload digest")
        if self.scope not in MEMORY_AUTHORITY_SCOPES:
            raise ValueError("Memory authority scope is invalid")
        if type(self.replayed) is not bool:
            raise TypeError("replayed must be a boolean")
        if (
            isinstance(self.receipt_version, bool)
            or not isinstance(self.receipt_version, int)
        ):
            raise TypeError("receipt_version must be an integer")
        if self.receipt_version != MEMORY_AUTHORITY_RECEIPT_VERSION:
            raise ValueError("Memory authority receipt version is unsupported")
        if not isinstance(self.materializations, tuple):
            raise TypeError("materializations must be a tuple")
        if not isinstance(self.rejected_claim_ids, tuple):
            raise TypeError("rejected_claim_ids must be a tuple")
        if (
            len(self.materializations)
            > MAX_MEMORY_MATERIALIZATIONS_PER_RECEIPT
        ):
            raise ValueError("Memory authority receipt has too many materializations")
        if (
            len(self.materializations) + len(self.rejected_claim_ids)
            > MAX_MEMORY_CLAIMS_PER_BATCH
        ):
            raise ValueError("Memory authority commit has too many claim outcomes")
        if not self.materializations and not self.rejected_claim_ids:
            raise ValueError("Memory authority commit must contain a claim outcome")

        claim_ids: set[str] = set()
        entry_ids: set[str] = set()
        scope_prefix = f"{self.scope}-"
        for materialization in self.materializations:
            if not isinstance(materialization, MemoryMaterialization):
                raise TypeError(
                    "materializations must contain MemoryMaterialization values"
                )
            if materialization.claim_id in claim_ids:
                raise ValueError("Memory authority commit repeats a claim ID")
            claim_ids.add(materialization.claim_id)
            if materialization.entry_id is not None:
                if not materialization.entry_id.startswith(scope_prefix):
                    raise ValueError(
                        "Memory materialization entry is outside the commit scope"
                    )
                if materialization.entry_id in entry_ids:
                    raise ValueError("Memory authority commit repeats an entry ID")
                entry_ids.add(materialization.entry_id)
            if any(
                not entry_id.startswith(scope_prefix)
                for entry_id in materialization.superseded_entry_ids
            ):
                raise ValueError(
                    "superseded Memory entry is outside the commit scope"
                )

        for claim_id in self.rejected_claim_ids:
            _require_claim_id(claim_id)
            if claim_id in claim_ids:
                raise ValueError("a Memory claim has multiple commit outcomes")
            claim_ids.add(claim_id)

    @property
    def authority_versions(self) -> tuple[tuple[str, str], ...]:
        """Project exact entry versions still materialized after this commit."""
        superseded = {
            entry_id
            for item in self.materializations
            for entry_id in item.superseded_entry_ids
        }
        return tuple(
            (item.entry_id, item.authority_digest)
            for item in self.materializations
            if item.remains_materialized
            and item.entry_id is not None
            and item.authority_digest is not None
            and item.entry_id not in superseded
        )

    @property
    def representative_id(self) -> str | None:
        """Return the first still-materialized entry in deterministic order."""
        versions = self.authority_versions
        return versions[0][0] if versions else None

    def as_replay(self) -> MemoryAuthorityCommit:
        """Return this exact receipt marked as a runtime replay."""
        return self if self.replayed else replace(self, replayed=True)

    def to_dict(self) -> dict[str, object]:
        """Return canonical receipt data; runtime replay state stays unpersisted."""
        return {
            "receiptVersion": self.receipt_version,
            "resultType": _AUTHORITY_RECEIPT_RESULT_TYPE,
            "operationId": self.operation_id,
            "payloadDigest": self.payload_digest,
            "scope": self.scope,
            "replayed": False,
            "materializations": [
                materialization.to_dict()
                for materialization in self.materializations
            ],
            "rejectedClaimIds": list(self.rejected_claim_ids),
        }

    def to_json(self) -> str:
        """Serialize the receipt to stable, canonical JSON."""
        encoded = json.dumps(
            self.to_dict(),
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
            allow_nan=False,
        )
        if len(encoded.encode()) > MAX_MEMORY_AUTHORITY_RECEIPT_BYTES:
            raise ValueError("Memory authority receipt exceeds its byte limit")
        return encoded

    @property
    def receipt_digest(self) -> str:
        """Return the stable lowercase SHA-256 digest of canonical receipt JSON."""
        return hashlib.sha256(self.to_json().encode()).hexdigest()

    @classmethod
    def from_dict(cls, value: object) -> MemoryAuthorityCommit:
        """Parse one closed canonical receipt mapping."""
        if not isinstance(value, Mapping) or set(value) != _AUTHORITY_COMMIT_FIELDS:
            raise ValueError("Memory authority receipt has an invalid schema")
        if value.get("resultType") != _AUTHORITY_RECEIPT_RESULT_TYPE:
            raise ValueError("Memory authority receipt result type is invalid")
        if value.get("replayed") is not False:
            raise ValueError("persisted Memory authority receipt cannot be replayed")
        raw_materializations = value.get("materializations")
        raw_rejected = value.get("rejectedClaimIds")
        if not isinstance(raw_materializations, list):
            raise TypeError("materializations must be a list")
        if not isinstance(raw_rejected, list):
            raise TypeError("rejectedClaimIds must be a list")
        return cls(
            receipt_version=value.get("receiptVersion"),  # type: ignore[arg-type]
            operation_id=value.get("operationId"),  # type: ignore[arg-type]
            payload_digest=value.get("payloadDigest"),  # type: ignore[arg-type]
            scope=value.get("scope"),  # type: ignore[arg-type]
            replayed=False,
            materializations=tuple(
                MemoryMaterialization.from_dict(item)
                for item in raw_materializations
            ),
            rejected_claim_ids=tuple(raw_rejected),
        )

    @classmethod
    def from_json(cls, content: object) -> MemoryAuthorityCommit:
        """Parse a bounded JSON receipt, rejecting duplicate object keys."""
        if not isinstance(content, str):
            raise TypeError("Memory authority receipt must be a JSON string")
        if len(content.encode()) > MAX_MEMORY_AUTHORITY_RECEIPT_BYTES:
            raise ValueError("Memory authority receipt exceeds its byte limit")

        def closed_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
            result: dict[str, object] = {}
            for key, value in pairs:
                if key in result:
                    raise ValueError(
                        "Memory authority receipt contains a duplicate JSON key"
                    )
                result[key] = value
            return result

        try:
            decoded = json.loads(content, object_pairs_hook=closed_object)
        except ValueError as exc:
            raise ValueError("Memory authority receipt is not valid JSON") from exc
        return cls.from_dict(decoded)


@dataclass(frozen=True, slots=True, kw_only=True)
class MemoryAuthorityReceiptReference:
    """Compact authority pointer to one immutable full commit receipt."""

    operation_id: str
    payload_digest: str
    scope: str
    blob: MemoryBlobReference
    reference_version: int = MEMORY_AUTHORITY_RECEIPT_REFERENCE_VERSION

    def __post_init__(self) -> None:
        _require_operation_id(self.operation_id)
        _require_digest(self.payload_digest, label="Memory payload digest")
        if self.scope not in MEMORY_AUTHORITY_SCOPES:
            raise ValueError("Memory authority scope is invalid")
        if not isinstance(self.blob, MemoryBlobReference):
            raise TypeError("blob must be a MemoryBlobReference")
        if (
            isinstance(self.reference_version, bool)
            or not isinstance(self.reference_version, int)
        ):
            raise TypeError("reference_version must be an integer")
        if (
            self.reference_version
            != MEMORY_AUTHORITY_RECEIPT_REFERENCE_VERSION
        ):
            raise ValueError("Memory receipt reference version is unsupported")

    @classmethod
    def from_commit(
        cls,
        commit: MemoryAuthorityCommit,
        blob: MemoryBlobReference,
    ) -> MemoryAuthorityReceiptReference:
        """Bind compact metadata to the exact canonical receipt blob."""

        if not isinstance(commit, MemoryAuthorityCommit):
            raise TypeError("commit must be a MemoryAuthorityCommit")
        if not isinstance(blob, MemoryBlobReference):
            raise TypeError("blob must be a MemoryBlobReference")
        expected_bytes = commit.to_json().encode("utf-8")
        if (
            blob.digest != commit.receipt_digest
            or blob.size_bytes != len(expected_bytes)
        ):
            raise ValueError("Memory receipt blob does not match its commit")
        return cls(
            operation_id=commit.operation_id,
            payload_digest=commit.payload_digest,
            scope=commit.scope,
            blob=blob,
        )

    def validate_commit(self, commit: MemoryAuthorityCommit) -> None:
        """Require a resolved blob to agree with every compact authority field."""

        if not isinstance(commit, MemoryAuthorityCommit):
            raise TypeError("commit must be a MemoryAuthorityCommit")
        expected_bytes = commit.to_json().encode("utf-8")
        if (
            commit.operation_id != self.operation_id
            or commit.payload_digest != self.payload_digest
            or commit.scope != self.scope
            or commit.receipt_digest != self.blob.digest
            or len(expected_bytes) != self.blob.size_bytes
        ):
            raise ValueError("Memory receipt reference does not match its blob")

    def to_dict(self) -> dict[str, object]:
        return {
            "referenceVersion": self.reference_version,
            "operationId": self.operation_id,
            "payloadDigest": self.payload_digest,
            "scope": self.scope,
            "blob": self.blob.to_dict(),
        }

    @classmethod
    def from_dict(cls, value: object) -> MemoryAuthorityReceiptReference:
        if (
            not isinstance(value, Mapping)
            or set(value) != _AUTHORITY_RECEIPT_REFERENCE_FIELDS
        ):
            raise ValueError("Memory receipt reference has an invalid schema")
        return cls(
            reference_version=value.get("referenceVersion"),  # type: ignore[arg-type]
            operation_id=value.get("operationId"),  # type: ignore[arg-type]
            payload_digest=value.get("payloadDigest"),  # type: ignore[arg-type]
            scope=value.get("scope"),  # type: ignore[arg-type]
            blob=MemoryBlobReference.from_dict(value.get("blob")),
        )


@dataclass(frozen=True, slots=True, kw_only=True)
class ProjectFactsEffect:
    """Content-free outcome of the advisory Project Facts side write."""

    status: str = "not_applicable"
    added_count: int = 0
    updated_count: int = 0
    failure_code: str | None = None

    def __post_init__(self) -> None:
        if self.status not in PROJECT_FACTS_EFFECT_STATUSES:
            raise ValueError("Project Facts effect status is invalid")
        added = _require_counter(
            self.added_count,
            label="Project Facts added_count",
        )
        updated = _require_counter(
            self.updated_count,
            label="Project Facts updated_count",
        )
        if added + updated > MAX_PROJECT_FACT_CHANGES_PER_WRITE:
            raise ValueError("Project Facts effect changes too many facts")
        if self.status == "committed":
            if added + updated == 0:
                raise ValueError("a committed Project Facts effect must change a fact")
            if self.failure_code is not None:
                raise ValueError("a committed Project Facts effect cannot fail")
            return
        if added or updated:
            raise ValueError(
                "only a committed Project Facts effect may report changes"
            )
        if self.status == "failed":
            if self.failure_code is None:
                raise ValueError("a failed Project Facts effect needs a failure code")
            _require_reason_code(
                self.failure_code,
                label="Project Facts failure code",
            )
        elif self.failure_code is not None:
            raise ValueError("only a failed Project Facts effect has a failure code")

    def to_dict(self) -> dict[str, object]:
        """Return the closed content-free Project Facts effect."""
        return {
            "status": self.status,
            "addedCount": self.added_count,
            "updatedCount": self.updated_count,
            "failureCode": self.failure_code,
        }

    @classmethod
    def from_dict(cls, value: object) -> ProjectFactsEffect:
        if not isinstance(value, Mapping) or set(value) != _PROJECT_FACTS_EFFECT_FIELDS:
            raise ValueError("Project Facts effect has an invalid schema")
        return cls(
            status=value.get("status"),  # type: ignore[arg-type]
            added_count=value.get("addedCount"),  # type: ignore[arg-type]
            updated_count=value.get("updatedCount"),  # type: ignore[arg-type]
            failure_code=value.get("failureCode"),  # type: ignore[arg-type]
        )


@dataclass(frozen=True, slots=True, kw_only=True)
class MemoryWriteResult:
    """Aggregate content-free outcome of one MemoryPipeline write attempt."""

    operation_id: str
    payload_digest: str
    authority_kind: str = "none"
    authority_commit: MemoryAuthorityCommit | None = None
    project_facts_effect: ProjectFactsEffect = field(
        default_factory=ProjectFactsEffect
    )
    reason_codes: tuple[str, ...] = ()
    post_commit_interrupted: bool = False
    result_version: int = MEMORY_WRITE_RESULT_VERSION

    def __post_init__(self) -> None:
        _require_operation_id(self.operation_id)
        _require_digest(self.payload_digest, label="Memory payload digest")
        if self.authority_kind not in MEMORY_AUTHORITY_KINDS:
            raise ValueError("Memory authority kind is invalid")
        if self.authority_commit is not None:
            if not isinstance(self.authority_commit, MemoryAuthorityCommit):
                raise TypeError(
                    "authority_commit must be a MemoryAuthorityCommit or None"
                )
            if self.authority_kind == "none":
                raise ValueError("authority_kind cannot be none when a commit exists")
            if self.authority_commit.operation_id != self.operation_id:
                raise ValueError("Memory authority commit operation ID does not match")
            if self.authority_commit.payload_digest != self.payload_digest:
                raise ValueError("Memory authority commit payload digest does not match")
            if (
                self.authority_kind == "conversation_fact"
                and self.authority_commit.scope != "user"
            ):
                raise ValueError("conversation facts require user authority")
        if not isinstance(self.project_facts_effect, ProjectFactsEffect):
            raise TypeError(
                "project_facts_effect must be a ProjectFactsEffect"
            )
        if not isinstance(self.reason_codes, tuple):
            raise TypeError("reason_codes must be a tuple")
        if len(self.reason_codes) > MAX_MEMORY_WRITE_REASON_CODES:
            raise ValueError("Memory write result has too many reason codes")
        seen_reasons: set[str] = set()
        for reason_code in self.reason_codes:
            _require_reason_code(reason_code, label="Memory write reason code")
            if reason_code in seen_reasons:
                raise ValueError("Memory write result repeats a reason code")
            seen_reasons.add(reason_code)
        if type(self.post_commit_interrupted) is not bool:
            raise TypeError("post_commit_interrupted must be a boolean")
        if isinstance(self.result_version, bool) or not isinstance(
            self.result_version, int
        ):
            raise TypeError("result_version must be an integer")
        if self.result_version != MEMORY_WRITE_RESULT_VERSION:
            raise ValueError("Memory write result version is unsupported")

    @property
    def authority_versions(self) -> tuple[tuple[str, str], ...]:
        """Return only entry versions still materialized after the write."""
        if self.authority_commit is None:
            return ()
        return self.authority_commit.authority_versions

    @property
    def representative_id(self) -> str | None:
        """Return the first still-materialized entry, if the write has one."""
        versions = self.authority_versions
        return versions[0][0] if versions else None


